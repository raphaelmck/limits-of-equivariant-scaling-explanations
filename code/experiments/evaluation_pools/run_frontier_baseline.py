"""Baseline-only forward-pass evaluation, no intervention, for arbitrary eSEN checkpoints over
the same frozen Neutral and support-matched pools at 16384 configurations. This is what
produces the matched-frontier comparison across all 102 pairs.

Reuses, unmodified: OwnerSpec, instantiate_model_generic, load_checkpoint_strict_generic
(pipeline.kernel.frontier_checkpoints), evaluation_data.build_batch /
per_atom_force_error, run_stage3a1_norm_control.per_config_accum -- exactly the same functions
run_gpu_eval.py already used for its baseline-only lmax2 pass. No new model/loss/pool logic.

Input: full_frontier_manifest.json (built by paper_repro/analysis_out/build_lmax24_all_frontier.py
derived matches; contains every unique lmax2/lmax4 checkpoint needed for the 102 valid matched
pairs). Configs: config_snapshots_full_frontier/ (generated by gen_full_frontier_configs.py,
override of sphere_channels only on top of the existing frozen stage3b1 templates -- see that
script's docstring).

Splits the manifest into shards (--shard i --num-shards N) so multiple independent sbatch jobs can
run concurrently within the same 03:00:00 partition=main / gpu:a100l:1 resource envelope as the
existing run_gpu_eval.sbatch template. Skips any checkpoint whose output row already exists in the
target JSONL (idempotent / resumable).
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

KPC_ROOT = Path("<PIPELINE_ROOT>")
sys.path.insert(0, str(KPC_ROOT))

import numpy as np
import torch
from fairchem.core.datasets import AseDBDataset

from pipeline.intervention import evaluation_data
from pipeline.kernel.frontier_checkpoints import (
    ARCH_LABEL, WIDTH_LABEL, INSTANTIATION_SEED, OwnerSpec,
    instantiate_model_generic, load_checkpoint_strict_generic,
)
from pipeline.intervention.run_norm_control import per_config_accum

OOD_ROOT = Path("<PROJECT_ROOT>/analysis_outputs/esen_irrep_ood_2026_08_22")
CFG_DIR = OOD_ROOT / "eval" / "config_snapshots_full_frontier"
OUT_DIR = OOD_ROOT / "eval" / "raw"
ID_POOL_PATH = OOD_ROOT / "id_pool" / "id_pool_indices.npy"
OOD_POOL_PATH = OOD_ROOT / "dataset" / "ood_pool_indices.npy"
OOD_VAL_SRC = "<CHECKPOINT_ROOT>/omol25/val"
MANIFEST_PATH = OOD_ROOT / "eval" / "full_frontier_manifest.json"

CHUNK = 32
M_MAX = 16384


def make_owner(lmax: int, rec: dict) -> OwnerSpec:
    tag = f"esen_lmax{lmax}_w{rec['width']}_s{rec['step']}"
    return OwnerSpec(
        tag=tag, architecture="esen", architecture_label=ARCH_LABEL["esen"],
        budget_label="full_frontier", width_label=WIDTH_LABEL["esen"],
        width=rec["width"], step=rec["step"], expected_n=rec["N"], D_atom_tokens=rec["D_atoms"],
        C_owner=rec["C_flops"], C_budget=rec["C_flops"], utilization=1.0, force_mse_norm=None,
        ckpt_path=rec["ckpt_path"],
        original_config_path=str(CFG_DIR / f"esen_lmax{lmax}_w{rec['width']}_generated.yaml"),
        config_name=f"esen_lmax{lmax}_w{rec['width']}_generated.yaml",
    )


def get_datasets():
    id_ds = AseDBDataset({"src": evaluation_data.VAL_PATH, "a2g_args": dict(r_energy=True, r_forces=True)})
    ood_ds = AseDBDataset({"src": OOD_VAL_SRC, "a2g_args": dict(r_energy=True, r_forces=True)})
    return {"ID": id_ds, "OOD": ood_ds}


def load_pool_indices(m_max):
    id_idx = np.load(ID_POOL_PATH)[:m_max].tolist()
    ood_idx = np.load(OOD_POOL_PATH)[:m_max].tolist()
    assert len(id_idx) == m_max and len(ood_idx) == m_max
    return {"ID": id_idx, "OOD": ood_idx}


def make_chunks(dataset, indices, device):
    return [evaluation_data.build_batch(dataset, indices[i:i + CHUNK], device) for i in range(0, len(indices), CHUNK)]


def already_done(out_path: Path, tag: str) -> set[str]:
    done = set()
    if out_path.exists():
        for line in open(out_path):
            try:
                d = json.loads(line)
            except json.JSONDecodeError:
                continue
            if d.get("tag") == tag:
                done.add(d["domain"])
    return done


def run_owner_baseline(lmax, rec, datasets, pool_idx, device, out_fh):
    owner = make_owner(lmax, rec)
    from pipeline.intervention.esen_intervention import ESenInterventionForward
    print(f"=== lmax{lmax} baseline {owner.tag} ===", flush=True)
    model, cfg, params = instantiate_model_generic(owner, device, INSTANTIATION_SEED)
    cp = load_checkpoint_strict_generic(model, owner, params)
    model.net.eval()
    fwd = ESenInterventionForward(model)

    for domain in ("ID", "OOD"):
        t0 = time.time()
        chunks = make_chunks(datasets[domain], pool_idx[domain], device)
        sums_all, counts_all = [], []
        for b in chunks:
            out_b, _ = fwd(b, intervention=None)
            pa = evaluation_data.per_atom_force_error(out_b["forces"], b)
            s, c = per_config_accum(pa, b)
            sums_all += s
            counts_all += c
        L_base = float(np.sum(sums_all) / max(np.sum(counts_all), 1))
        print(f"  [{domain}] L={L_base:.8f} ({time.time()-t0:.1f}s)", flush=True)
        out_fh.write(json.dumps({
            "tag": owner.tag, "lmax": lmax, "domain": domain, "width": owner.width,
            "step": owner.step, "C_flops": owner.C_owner, "kind": "lmax{}_baseline_full_frontier".format(lmax),
            "m_eval": len(pool_idx[domain]), "L_baseline": L_base,
            "per_config_sum": sums_all, "per_config_natoms": counts_all,
            "checkpoint_sha256": cp.get("checkpoint_sha256"), "dtype": "float32",
            "wall_seconds": time.time() - t0,
        }, default=str) + "\n")
        out_fh.flush()
        del chunks
        if device == "cuda":
            torch.cuda.empty_cache()
    del model, fwd
    if device == "cuda":
        torch.cuda.empty_cache()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shard", type=int, default=0)
    ap.add_argument("--num-shards", type=int, default=1)
    ap.add_argument("--smoke-test", action="store_true")
    args = ap.parse_args()
    m_max = 16 if args.smoke_test else M_MAX

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"device={device} shard={args.shard}/{args.num_shards} smoke={args.smoke_test}", flush=True)

    manifest = json.loads(MANIFEST_PATH.read_text())
    jobs = []
    for rec in manifest["lmax4"]:
        if rec["already_evaluated_canonical"]:
            continue
        jobs.append((4, rec))
    for rec in manifest["lmax2"]:
        if rec["already_evaluated_canonical"]:
            continue
        jobs.append((2, rec))
    jobs.sort(key=lambda t: (t[0], t[1]["width"], t[1]["step"]))
    my_jobs = jobs[args.shard::args.num_shards]
    print(f"total jobs={len(jobs)}, this shard handles {len(my_jobs)}", flush=True)

    suffix = "_smoke" if args.smoke_test else ""
    out_path = OUT_DIR / f"full_frontier_baseline_shard{args.shard}{suffix}.jsonl"

    datasets = get_datasets()
    pool_idx = load_pool_indices(m_max)

    with open(out_path, "a") as out_fh:
        for lmax, rec in my_jobs:
            tag = f"esen_lmax{lmax}_w{rec['width']}_s{rec['step']}"
            done = already_done(out_path, tag)
            if done >= {"ID", "OOD"}:
                print(f"skip (already done) {tag}", flush=True)
                continue
            run_owner_baseline(lmax, rec, datasets, pool_idx, device, out_fh)

    print(f"DONE shard {args.shard} -> {out_path}", flush=True)


if __name__ == "__main__":
    main()
